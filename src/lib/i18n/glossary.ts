const EN_GLOSSARY = GLOSSARY.en ?? {};

/**
 * Resolve a glossary concept for a locale. Falls back to the English term, so
 * tool names built from glossary terms never render a raw concept key.
 */
export function term(locale: LocaleCode, concept: GlossaryConcept): string {
  return GLOSSARY[locale]?.[concept] ?? EN_GLOSSARY[concept] ?? concept;
}

/**
 * Map a ready-tool slug to the primary concept noun it represents (when its
 * name is built from a glossary concept), or `null` when the slug carries no
 * mapped concept. Used by the localization validator to check terminology
 * consistency and by any caller that needs a tool's localized concept label.
 */
const CONCEPT_BY_SUFFIX: Partial<Record<string, GlossaryConcept>> = {
  compressor: "compress",
  converter: "converter",
  generator: "generator",
  formatter: "formatter",
  viewer: "viewer",
  reader: "reader",
  checker: "checker",
  parser: "parser",
  tester: "tester",
  minifier: "minifier",
  calculator: "calculator",
  counter: "counter",
};

export function conceptForSlug(slug: string): GlossaryConcept | null {
  for (const [suffix, concept] of Object.entries(CONCEPT_BY_SUFFIX)) {
    if (concept && slug.endsWith(suffix)) return concept;
  }
  return null;
}

/**
 * Resolve the localized concept noun for a ready tool, e.g. the "formatter"
 * concept for `json-formatter` in a given locale. Returns the English term
 * (concept itself) when no glossary entry exists, so callers never receive a
 * raw key. This is the runtime entry point that makes the glossary a live,
 * reusable terminology source rather than a static reference.
 */
export function toolConceptTerm(locale: LocaleCode, slug: string): string {
  const concept = conceptForSlug(slug);
  return concept ? term(locale, concept) : slug;
}
