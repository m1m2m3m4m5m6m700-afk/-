import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const runtimeRegistryPath = path.join(root, "src/lib/tool-runtime/readyTools.ts");
const runtimeDir = path.join(root, "src/lib/tool-runtime/tools");
const routeDir = path.join(root, "src/routes/tools");
const catalogPath = path.join(root, "src/lib/desktop-tools/verifiedCatalog.ts");

const issues = [];
const registry = fs.readFileSync(runtimeRegistryPath, "utf8");
const catalog = fs.readFileSync(catalogPath, "utf8");

const publicImports = [...registry.matchAll(/import\s+\{\s*([A-Za-z0-9_]+)\s*\}\s+from\s+"\.\/tools\/([^\"]+)"/g)]
  .map((m) => ({ symbol: m[1], slug: m[2] }));

const publicSymbols = new Set(publicImports.map((entry) => entry.symbol));
const publicSlugs = new Set(publicImports.map((entry) => entry.slug));

const registryMatch = registry.match(/export const readyToolRuntimes = \[([\s\S]*?)\]\s+as const/);
const registeredSymbols = registryMatch
  ? [...registryMatch[1].matchAll(/([A-Za-z0-9_]+)Runtime/g)].map((m) => m[1] + "Runtime")
  : [];

for (const symbol of registeredSymbols) {
  if (!publicSymbols.has(symbol)) issues.push(`Registry references ${symbol}, but its runtime import is missing.`);
}
for (const entry of publicImports) {
  if (!fs.existsSync(path.join(runtimeDir, `${entry.slug}.tsx`)) && !fs.existsSync(path.join(runtimeDir, `${entry.slug}.ts`))) {
    issues.push(`Public runtime ${entry.slug} has no runtime source file.`);
  }
  if (!fs.existsSync(path.join(routeDir, `${entry.slug}.tsx`))) {
    issues.push(`Public runtime ${entry.slug} is missing route src/routes/tools/${entry.slug}.tsx.`);
  }
  const sourcePath = fs.existsSync(path.join(runtimeDir, `${entry.slug}.tsx`))
    ? path.join(runtimeDir, `${entry.slug}.tsx`)
    : path.join(runtimeDir, `${entry.slug}.ts`);
  const source = fs.readFileSync(sourcePath, "utf8");
  if (!new RegExp(`toolId:\\s*"[^"]+"`).test(source)) issues.push(`Runtime ${entry.slug} is missing toolId.`);
  if (!new RegExp(`slug:\\s*"${entry.slug}"`).test(source)) issues.push(`Runtime ${entry.slug} slug does not match its public registry slug.`);
  for (const signature of ["Processed Result for this tool", "Processed file:", "Output generated by", "Everything processed locally"]) {
    if (source.includes(signature)) issues.push(`Runtime ${entry.slug} contains fake implementation signature: ${signature}.`);
  }
}

const readyBlock = (registry.match(/readyToolRuntimes = \[([\s\S]*?)\]\s+as const/)?.[1] ?? "").trim();
const readyCount = readyBlock ? readyBlock.split(",").map((v) => v.trim()).filter(Boolean).length : 0;
const catalogReadyEntries = [...catalog.matchAll(/status:\s*"ready"[\s\S]*?slug:\s*"([^"]+)"/g)].map((m) => m[1]);
for (const slug of catalogReadyEntries) if (!publicSlugs.has(slug)) issues.push(`Desktop catalog marks ${slug} ready but it is not publicly promoted in readyTools.ts.`);

if (issues.length > 0) throw new Error(`Public tool runtime validation failed with ${issues.length} issue(s).\n- ${issues.join("\n- ")}`);
console.log(`Public tool runtime validation passed: ${readyCount} promoted runtime(s). Legacy runtime files are intentionally ignored until promoted.`);
