import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const manifestSource = fs.readFileSync(path.join(root, "src/lib/tool-platform/publicDesktopTools.ts"), "utf8");
const readyToolsRegistrySource = fs.readFileSync(path.join(root, "src/lib/tool-runtime/readyTools.ts"), "utf8");
const runtimeDir = path.join(root, "src/lib/tool-runtime/tools");
const routeDir = path.join(root, "src/routes/tools");

const issues = [];
const publicEntries = [];
const manifestPattern = /id:\s*"([^"]+)"[\s\S]*?slug:\s*"([^"]+)"[\s\S]*?category:\s*"([^"]+)"/g;
for (const match of manifestSource.matchAll(manifestPattern)) {
  publicEntries.push({ id: match[1], slug: match[2], categoryId: match[3] });
}

if (publicEntries.length === 0) issues.push("Public Tool Platform manifest contains no tools.");

const publicIds = new Set(publicEntries.map((entry) => entry.id));
const publicSlugs = new Set(publicEntries.map((entry) => entry.slug));

const registeredImports = [...readyToolsRegistrySource.matchAll(/from\s+"\.\/tools\/([^"]+)"/g)].map((match) => match[1]);
const runtimeFilesByBaseName = new Map(
  fs.readdirSync(runtimeDir)
    .filter((file) => file.endsWith(".ts") || file.endsWith(".tsx"))
    .map((file) => [file.replace(/\.(?:ts|tsx)$/, ""), file]),
);

const fakeSignatures = ["Processed Result for this tool", "Processed file:", "Output generated by", "Everything processed locally"];

function hasFakeSetTimeout(source) {
  return /setTimeout\s*\([\s\S]{0,600}?set(Result|Output|Content|Value)\s*\(/.test(source);
}

for (const baseName of registeredImports) {
  const file = runtimeFilesByBaseName.get(baseName);
  if (!file) {
    issues.push(`Registered public runtime ${baseName} is missing a source file under src/lib/tool-runtime/tools/.`);
    continue;
  }
  const source = fs.readFileSync(path.join(runtimeDir, file), "utf8");
  const slug = source.match(/slug:\s*"([^"]+)"/)?.[1];
  const toolId = source.match(/toolId:\s*"([^"]+)"/)?.[1];
  const categoryId = source.match(/categoryId:\s*"([^"]+)"/)?.[1];
  if (!slug || !toolId || !categoryId) {
    issues.push(`Runtime ${file} is missing toolId, slug, or categoryId.`);
    continue;
  }
  if (!publicIds.has(toolId)) issues.push(`Runtime ${file} is not backed by a public Tool Platform registration: ${toolId}.`);
  if (!publicSlugs.has(slug)) issues.push(`Runtime ${file} uses a slug not present in the public manifest: ${slug}.`);
  const manifestEntry = publicEntries.find((entry) => entry.id === toolId);
  if (manifestEntry && manifestEntry.categoryId !== categoryId) {
    issues.push(`Runtime ${file} category ${categoryId} does not match manifest category ${manifestEntry.categoryId}.`);
  }
  if (!fs.existsSync(path.join(routeDir, `${slug}.tsx`))) {
    issues.push(`Public runtime ${slug} is missing route file src/routes/tools/${slug}.tsx.`);
  }
  for (const signature of fakeSignatures) if (source.includes(signature)) issues.push(`Runtime ${file} contains fake implementation signature: "${signature}".`);
  if (hasFakeSetTimeout(source)) issues.push(`Runtime ${file} uses setTimeout to fabricate processing output.`);
}

for (const entry of publicEntries) {
  const matches = registeredImports.filter((baseName) => baseName === entry.slug);
  if (matches.length === 0) issues.push(`Public tool ${entry.id} is missing a registered runtime import.`);
  if (matches.length > 1) issues.push(`Public tool ${entry.id} has duplicate runtime imports.`);
}

if (issues.length > 0) {
  throw new Error(`Tool runtime validation failed with ${issues.length} issue(s).\n- ${issues.join("\n- ")}`);
}

console.log(`Tool runtime validation passed: ${registeredImports.length} public runtimes for ${publicEntries.length} public tools.`);
