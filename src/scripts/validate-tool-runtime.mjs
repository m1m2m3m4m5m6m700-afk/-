import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const registrySource = fs.readFileSync(path.join(root, "src/config/tools.ts"), "utf8");
const readyToolsRegistrySource = fs.readFileSync(path.join(root, "src/lib/tool-runtime/readyTools.ts"), "utf8");
const runtimeDir = path.join(root, "src/lib/tool-runtime/tools");
const routeDir = path.join(root, "src/routes/tools");

const issues = [];
const publicEntries = [...registrySource.matchAll(/\{\s*id:\s*"([^"]+)"[\s\S]*?category:\s*"([^"]+)"[\s\S]*?path:\s*"([^"]+)"[\s\S]*?isReady:\s*(true|false),/g)]
  .filter((match) => match[4] === "true")
  .map((match) => ({ id: match[1], categoryId: match[2], path: match[3], slug: match[1] }));

if (publicEntries.length === 0) issues.push("Central tool registry contains no ready tools.");
if (!readyToolsRegistrySource.includes("getReadyToolConfigs().map(toolConfigToRuntime)")) {
  issues.push("Ready runtime is not derived from the central tool registry.");
}

const publicIds = new Set(publicEntries.map((entry) => entry.id));
const publicSlugs = new Set(publicEntries.map((entry) => entry.slug));
const hasDynamicToolRoute = fs.existsSync(path.join(routeDir, "$slug.tsx"));
if (!hasDynamicToolRoute) issues.push("Dynamic tool route src/routes/tools/$slug.tsx is missing.");

const fakeSignatures = ["Processed Result for this tool", "Processed file:", "Output generated by", "Everything processed locally"];
function hasFakeSetTimeout(source) {
  return /setTimeout\s*\([\s\S]{0,600}?set(Result|Output|Content|Value)\s*\(/.test(source);
}

for (const entry of publicEntries) {
  const file = path.join(runtimeDir, `${entry.id}.tsx`);
  if (!fs.existsSync(file)) {
    issues.push(`Ready public runtime ${entry.id} is missing from src/lib/tool-runtime/tools/.`);
    continue;
  }
  const source = fs.readFileSync(file, "utf8");
  for (const signature of fakeSignatures) {
    if (source.includes(signature)) issues.push(`Runtime ${entry.id}.tsx contains fake implementation signature: "${signature}".`);
  }
  if (hasFakeSetTimeout(source)) issues.push(`Runtime ${entry.id}.tsx uses setTimeout to fabricate processing output.`);
  if (!publicIds.has(entry.id) || !publicSlugs.has(entry.slug)) issues.push(`Invalid ready tool registration: ${entry.id}.`);
}

if (issues.length > 0) throw new Error(`Tool runtime validation failed with ${issues.length} issue(s).\n- ${issues.join("\n- ")}`);
console.log(`Tool runtime validation passed: ${publicEntries.length} ready tools from the central registry using the dynamic tool route.`);
