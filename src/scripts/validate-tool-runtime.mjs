import fs from "node:fs";
import path from "node:path";

const root = process.cwd();
const runtimeDir = path.join(root, "src/lib/tool-runtime/tools");
const routeDir = path.join(root, "src/routes/tools");
const readyRegistryPath = path.join(root, "src/lib/tool-runtime/readyTools.ts");

const registrySource = fs.readFileSync(readyRegistryPath, "utf8");
const runtimeEntries = [];
const issues = [];

for (const match of registrySource.matchAll(/import\s+(\w+)\s+from\s+"\.\/tools\/([^"]+)";/g)) {
  runtimeEntries.push({ exportName: match[1], slug: match[2] });
}

if (runtimeEntries.length === 0) {
  issues.push("Public runtime registry contains no promoted tools.");
}

const duplicateSlugs = runtimeEntries
  .map((entry) => entry.slug)
  .filter((slug, index, values) => values.indexOf(slug) !== index);
for (const slug of new Set(duplicateSlugs)) issues.push(`Duplicate public runtime slug: ${slug}.`);

const arraySection = registrySource.match(/export const readyToolRuntimes = \[([\s\S]*?)\];/);
const registeredExports = new Set(
  arraySection ? [...arraySection[1].matchAll(/\b([A-Za-z_$][\w$]*)\b/g)].map((match) => match[1]) : [],
);

for (const entry of runtimeEntries) {
  if (!registeredExports.has(entry.exportName)) {
    issues.push(`Runtime ${entry.slug} is imported but not promoted in readyToolRuntimes.`);
    continue;
  }

  const runtimePath = path.join(runtimeDir, `${entry.slug}.tsx`);
  const runtimeJsPath = path.join(runtimeDir, `${entry.slug}.ts`);
  const sourcePath = fs.existsSync(runtimePath) ? runtimePath : runtimeJsPath;
  if (!fs.existsSync(sourcePath)) {
    issues.push(`Public runtime ${entry.slug} is missing its implementation file.`);
    continue;
  }

  const source = fs.readFileSync(sourcePath, "utf8");
  const slugMatch = source.match(/slug:\s*"([^"]+)"/);
  const toolIdMatch = source.match(/toolId:\s*"([^"]+)"/);
  if (!slugMatch) issues.push(`Runtime ${entry.slug} is missing its slug.`);
  else if (slugMatch[1] !== entry.slug) issues.push(`Runtime ${entry.slug} declares slug ${slugMatch[1]}.`);
  if (!toolIdMatch) issues.push(`Runtime ${entry.slug} is missing its toolId.`);

  if (!fs.existsSync(path.join(routeDir, `${entry.slug}.tsx`))) {
    issues.push(`Public runtime ${entry.slug} is missing route file src/routes/tools/${entry.slug}.tsx.`);
  }

  for (const signature of [
    "Processed Result for this tool",
    "Processed file:",
    "Output generated by",
    "Everything processed locally",
  ]) {
    if (source.includes(signature)) issues.push(`Runtime ${entry.slug} contains fake implementation signature: "${signature}".`);
  }

  if (/setTimeout\s*\([\s\S]{0,500}set(Result|Output|Content|Value)\s*\(/.test(source)) {
    issues.push(`Runtime ${entry.slug} appears to fabricate processing output with setTimeout.`);
  }
}

if (issues.length) {
  throw new Error(
    `Public tool runtime validation failed with ${issues.length} issue(s).\n- ${issues.join("\n- ")}`,
  );
}

console.log(`Public tool runtime validation passed: ${runtimeEntries.length} promoted runtimes.`);
